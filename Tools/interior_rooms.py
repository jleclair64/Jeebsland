def face(x, y, tx, ty): return math.degrees(math.atan2(ty - y, tx - x)) - 90.0   # (a chair's front is its +Y)
def seat(R, mesh, x, y, tx, ty, **k):
    p = R.put(mesh, x, y, 0, face(x, y, tx, ty), **k); p.ok = True; return p
def rug(R, n, x, y, sc, yaw=0): return R.put(T + "Carpet_00%d" % n, x, y, 0.3, yaw, (sc, sc, 1), kind="flat", solid=False)
def chandelier(R, x, y, lm=300): return R.put(T + "Lamp_001", x, y, H - 8 - 44.2 * 0.45, 0, 0.45, kind="free", light=lm, radius=650)
def on(R, base, mesh, dx=0, dy=0, yaw=0, **k): return R.put(mesh, dx, dy, 0, yaw, on=base, **k)
def shelf(R, side, along, z, items=(), **k):
    """A wall shelf with small things along it (items: (mesh, offset along the shelf, yaw))."""
    s = R.wall(side, T + "Shelf_002", along, z, gap=0, **k)
    for mesh, off, yaw in items:
        ax = (off, 0) if side in "NS" else (0, off)
        R.put(mesh, s.cx + ax[0], s.cy + ax[1], s.top - 0.5, yaw, kind="free")   # (the board's top is the model's top)
    return s
def wall_lamp(R, side, along, z=175, lm=110): return R.wall(side, T + "Lamp_002", along, z, gap=0, light=lm, radius=300)
def hang(R, side, mesh, along, z, turn=0, **k): return R.wall(side, mesh, along, z, gap=0.5, turn=turn, **k)
def bed(R, x, y, yaw=0, sc=1.0): return R.put(I("Bed"), x, y, 0, yaw, sc)
def fireside(R, chairs=(T + "Chair_001", T + "Chair_001"), carpet=1):
    rug(R, carpet, -235, -50, 0.6)
    if chairs[0]: seat(R, chairs[0], -230, 65, -385, -50)
    if len(chairs) > 1 and chairs[1]: seat(R, chairs[1], -230, -165, -385, -50)

